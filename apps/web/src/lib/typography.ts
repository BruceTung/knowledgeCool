/**
 * 界面字号刻度(v2.6)。
 *
 * ## 为什么要有这个文件
 *
 * 用户**两次**指出「字体太小」「字样不对称」。第一次我按处调了一遍,第二次还是不够 ——
 * 因为**没有刻度**:9px / 10px / 11px / 12px / 13px / 14px 六个档混着用,谁写都行。
 * 于是同一屏里左栏 13px、右栏 12px、角标 10px、正文 15px,看起来就是"不成比例"。
 *
 * 所以这里定死刻度,并有 `typography.test.ts` **扫描源码**拦住越界 ——
 * 从此字号不是"看着办",而是一条能被机器检查的规则。
 *
 * ## 刻度(只有四档)
 *
 * | 层 | 值 | 写法 | 用途 |
 * |---|---|---|---|
 * | 正文 | 15px | `.kc-prose`(`styles.css`) | 编辑器里的文档本体 |
 * | **内容** | **14px** | `text-sm` / `T_BODY` | 组织树的行、右栏目录项、评论正文、卡片标题 |
 * | **次级** | **12px** | `text-xs` | 表单标签、提示、时间、说明文字、tab、面包屑 |
 * | **徽章** | **11px** | `T_BADGE` | 「部/组/页」、评论数、「已离职」、`Ctrl K` |
 * | ~~10px 及以下~~ | **禁止** | — | 屏上最小就是 11px |
 *
 * ## 为什么只有四档 —— 而且**刻意不留 13px**
 *
 * 起草这份刻度时我先写了五档,给"次级信息"单开了一个 13px。
 * 写完才发现代码里已经有 **64 处 `text-xs`(12px)** —— 那第五档要么全改(大改且没必要),
 * 要么就成了一纸空文。
 *
 * **多一档就多一次分歧的机会**,而这份刻度存在的全部理由就是消灭分歧。
 * 所以退回四档:13px 不用,次级一律 12px。
 *
 * 证据也支持这么做:那 64 处 12px 用户**从没提过**(他指的是"左栏/右栏的内容"),说明
 * 12px 作为次级信息是可接受的;真正错的是**内容级文字被压到 12–13px** —— 那是要被
 * **读**的东西,却和标签一个尺寸。
 *
 * ## 唯一的任意值
 *
 * 全项目只允许 **一个** 任意值字号:`text-[11px]`(徽章)。别的尺寸一律走
 * Tailwind 具名档(`text-xs` / `text-sm` / `text-base` / `text-lg` / `text-xl` …)。
 * 具名档有内在比例,而随手写死的像素值没有 —— 上面那六个档就是这么来的。
 *
 * ## 判断规则(定刻度时真正要回答的那一个问题)
 *
 * **它是"内容"还是"标签"?**
 *
 *   · 内容(要被**读**:列表项、正文块、评论、目录)→ 14px
 *   · 标签(要被**认出**:名字、时间、提示、徽章)→ 12px,最小 11px
 *
 * 左栏的树行之所以两次被指"太小",就是因为它明明是内容,却按标签的尺寸在写。
 */

/** 内容级:组织树的行、右栏目录项、评论正文、卡片标题 */
export const T_BODY = 'text-sm';

/** 徽章与角标:类型标、评论数、「已离职」、快捷键提示 */
export const T_BADGE = 'text-[11px]';

/**
 * 允许出现在源码里的任意值字号(像素)。
 *
 * **只有这一个。** 想加新值之前先问上面那个问题:它是内容还是标签?
 * 二者的答案分别指向 14 与 12,中间不需要第五档。
 */
export const ALLOWED_ARBITRARY_PX = [11] as const;

/** 屏上允许的最小字号。低于它的一律视为笔误或"局部妥协",不接受。 */
export const MIN_FONT_PX = 11;
