/**
 * 界面字号刻度(v2.8)。
 *
 * ## 为什么要有这个文件
 *
 * 用户**三次**说字体太小。前两次我都在拍脑袋调数值 —— 第一次调了控件尺寸,
 * 第二次定了个"四档刻度"但**没有外部依据**,把最小档定成 11px、
 * 把 tab / 目录 / 评论这些**组件级文字**当"次级信息"塞进 12px。
 * 用户的原话是「你能不能找几个好点的网站去参考一下…或者直接去看看 confluence 是如何做的」。
 *
 * 所以这一次先查参照,再定刻度。依据是两份公开的设计规范:
 *
 * ## 参照一:Atlassian Design System(Confluence 用的就是它)
 *
 * | Token | 字号 / 行高 | 官方说明 |
 * |---|---|---|
 * | `font.body.large` | **16 / 24** | 长文阅读的默认档(博客、文档) |
 * | `font.body` | **14 / 20** | **组件里的默认档**;"配合图标时用 Medium(500) 字重" |
 * | `font.body.small` | **12 / 16** | "**谨慎使用**,仅用于次级内容,如细字印刷" |
 * | `font.code` | 12 / 20 | 代码块 |
 *
 * Confluence 更新日志里还有一句关键的话:视觉改版"把最小的标题与正文字号
 * **从 11px 提到 12px**"。也就是说 **11px 低于 Atlassian 自己的下限**。
 *
 * ## 参照二:Ant Design(中文界面,更贴近本项目)
 *
 * - 基础字号**从 12 提到 14**,理由是"基于 50cm 阅读距离与最佳阅读角度"。
 * - 推荐正文 14 / 行高 22;辅助文字 12 / 行高 20。
 * - **中文字体行高要在 1.5–1.8 之间**(汉字密实且高度一致,比西文需要更大行高)。
 * - "字阶的选择尽量控制在 **3–5 种**之间,保持克制"。
 *
 * ## 由此得到的刻度(四档,与 Tailwind 具名档一一对应)
 *
 * | 层 | 值 | 写法 | 依据 |
 * |---|---|---|---|
 * | 文档正文 | **16px / 1.75** | `.kc-prose`(`styles.css`) | ADS `body.large` 16/24;Confluence 编辑器正文也是 16px |
 * | **内容**:树行、目录项、评论正文、搜索框 | **14px / 20px** | `text-sm` | ADS `font.body` —— **组件默认档** |
 * | **组件标签**:tab、按钮、字段标签、面包屑、元信息 | **14px / 20px** + `font-medium` | `text-sm font-medium` | ADS:「组件里用 14px;配合图标时用 Medium」 |
 * | **元信息 / 徽章 / 角标** | **12px / 16px** | `text-xs` | ADS `body.small` —— 仅用于细字印刷(计数、快捷键提示、状态标签) |
 *
 * 三档都落在 Tailwind 的具名档上(`text-xs` = 12/16、`text-sm` = 14/20),
 * 恰好与 ADS 的 `body.small` / `font.body` **数值完全一致**。
 * 所以这里**不再需要任何任意值字号** —— 见下方"唯一规则"。
 *
 * ## ⚠️ 上一轮的两个错误(写下来免得再犯)
 *
 * 1. **最小不是 11px,是 12px。** Atlassian 特意从 11 提到了 12。
 * 2. **tab / 目录 / 评论不是"细字印刷",是组件级文字,应该用 14px。**
 *    判据不是"它重不重要",而是"它是不是**要被读/被点的界面文字**"。
 *    真正的 12px 只剩:计数、快捷键提示、状态徽章这类**一眼扫过**的东西。
 *
 * ## 唯一规则(由 `typography.test.ts` 扫描源码执行)
 *
 * **任何地方都不允许写任意值字号**(`text-[13px]` 之类)。
 * 只有 `.kc-prose` 的 16px 是例外 —— 它在 `styles.css` 里,不在组件代码中。
 *
 * 理由:任意值一旦允许,就会重新出现 9 / 10 / 11 / 12 / 13 并存;
 * 而具名档有内在比例,且与上面两份规范对得上。
 */

/** 内容级:组织树的行、右栏目录项、评论正文、搜索框里的内容 */
export const T_BODY = 'text-sm';

/**
 * **导航级:组织树的行**(v2.17)。
 *
 * ⚠️ 这一档是被用户**第四次**说"太小"之后加的,所以把缘由写清楚 ——
 * 前三次的教训都在文件头,而"树行"恰恰是当时被判成"组件级 14px"的那一类。
 *
 * 为什么树行单独用 16px 而不是跟着 `T_BODY` 的 14px:
 *
 * · **它是导航,不是内容。** ADS 把 14px 定为"组件里的默认档",针对的是
 *   按钮 / 表单 / tab 这类**局部**控件;而组织树是整页左侧的**主导航**,
 *   用户一天要点几十次,并且要在同一列里比较"哪个是组、哪个是页面"。
 *   Confluence / Notion / VS Code 的文件树都**比正文按钮大一档**。
 * · 它落在 Tailwind 的具名档上(`text-base` = 16/24),**不是任意值** ——
 *   所以文件末尾那条"不允许任意值字号"的规则照旧成立。
 * · 16px 与文档正文同档,于是"左树挑一篇 → 右边读它"两处字号一致,
 *   视线来回切换时不用重新适应。
 *
 * 行高也一起放大了(见 `OrgTreePanel` 的 `ROW_CLASS`:36px → 44px)——
 * 只放大字号而不放开行高,字会挤在一起,反而更难读。
 */
export const T_NAV = 'text-base';

/** 组件标签:tab、按钮、字段标签、面包屑、元信息 —— 与内容同尺寸,靠字重区分 */
export const T_LABEL = 'text-sm font-medium';

/** 元信息 / 徽章 / 角标:计数、快捷键提示、状态标签 —— 仅此一类允许 12px */
export const T_META = 'text-xs';

/** 屏上允许的最小字号。Atlassian 把最小字号从 11 提到了 12。 */
export const MIN_FONT_PX = 12;

